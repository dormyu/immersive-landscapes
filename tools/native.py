#!/usr/bin/env python3
"""Prepare our source bundle and build it with the already adapted DH on E:."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "mixins/immersive_landscapes"


def generate():
    parts = ["// Generated by tools/native.py from the original MIT sources; do not edit.\n"]
    for name in ("terrain", "drainage", "sampling"):
        source = (ROOT / f"src/{name}.rs").read_text(encoding="utf-8")
        parts.append(f"#[allow(dead_code)]\npub mod {name} {{\n{source}\n}}\n")
    parts.append("pub use terrain::{Climate, Config, HeightField};\n")
    parts.append("pub use drainage::Basin;\npub use sampling::{Landscape, Surface};\n")
    (BUNDLE / "core.generated.rs").write_text("".join(parts), encoding="utf-8", newline="\n")


def package():
    out = ROOT / "target/immersive-landscapes-0.1.0-dev.1.hnmod"
    out.parent.mkdir(parents=True, exist_ok=True)
    manifest = {
        "schema": 1, "id": "immersive_landscapes", "name": "Immersive Landscapes",
        "version": "0.1.0-dev.1", "authors": ["dormyu"], "license": "MIT",
        "game": "26.3",
        "horizon": json.loads((ROOT / "compatibility.json").read_text())["horizon_revision"],
        "mixins": json.loads((ROOT / "compatibility.json").read_text())["horizon_mixins_revision"],
    }
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("horizon-native.json", json.dumps(manifest, indent=2))
        for path in sorted(BUNDLE.iterdir()):
            if path.suffix in (".rs", ".toml"):
                archive.write(path, "mixins/immersive_landscapes/" + path.name)
        for name in ("LICENSE", "CREDITS.md", "compatibility.json"):
            archive.write(ROOT / name, name)
        for name in ("docs/native-build.md", "tools/patches/horizon-mixins-boundary-head.patch", "third-party/horizon-mixins-LICENSE"):
            archive.write(ROOT / name, name)
    print(f"{out} sha256={hashlib.sha256(out.read_bytes()).hexdigest()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("generate", "stage", "check", "build", "package"))
    args = parser.parse_args()
    generate()
    if args.action == "generate":
        print(BUNDLE)
    elif args.action == "package":
        package()
    else:
        dev = ROOT.parent / "RustCore/development"
        os.environ["HORIZON_MIXINS_BIN"] = str(dev / "mixins-tool/bin/horizon-mixins.exe")
        if args.action == "build":
            command = [sys.executable, "-X", "utf8", str(dev / "scripts/Run-GuardedBuild.py"), "--with", str(BUNDLE)]
        else:
            command = [sys.executable, "-X", "utf8", str(dev / "distant-horizons/tools/horizon.py"), args.action, "--with", str(BUNDLE)]
        if os.environ.get("CARGO_BUILD_JOBS") != "1" or not Path(os.environ.get("TEMP", "/")).resolve().is_relative_to(dev):
            raise SystemExit("Source RustCore/development/scripts/Enter-RustDev.ps1 first (all temp/cache on E, jobs=1).")
        raise SystemExit(subprocess.call(command, cwd=dev))


if __name__ == "__main__":
    main()
